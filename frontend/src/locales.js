export function translate(locale,key,values={}) {
 const resource=resources[locale]||resources.en;
 return (resource[key]||resources.en[key]||key).replace(/\{(\w+)\}/g,(_,name)=>typeof values[name]==='number'?new Intl.NumberFormat(locale).format(values[name]):String(values[name]??''));
}
export function localizedError(locale,error) {
 const code=typeof error==='string'?error:error?.code;
 return translate(locale,resources.en['error.'+code]?'error.'+code:'error.UNKNOWN');
}
