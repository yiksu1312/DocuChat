import {test,expect} from '@playwright/test';
import path from 'node:path';
import {mkdir} from 'node:fs/promises';
test.beforeEach(async({request})=>{
 for(const d of (await (await request.get('/api/documents')).json()).documents) await request.delete('/api/documents/'+d.documentId);
});
test('English default, persistent preference, unchanged session and scope, localized errors and documentation screenshots',async({page})=>{
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Documents',exact:true})).toBeVisible();
 await expect(page.locator('html')).toHaveAttribute('lang','en');
 await page.locator('input[type=file]').setInputFiles(path.resolve('fixtures/orchid.pdf'));
 await expect(page.locator('.document-item')).toContainText('Available');
 await page.getByRole('button',{name:'New session',exact:true}).click();
 await page.getByRole('textbox',{name:'Document question'}).fill('What is the launch code?');
 await page.getByRole('button',{name:'Ask',exact:true}).click();
 await expect(page.locator('.answer').last()).toContainText('ORCHID-742');
 await expect(page.getByText('Includes references · Check the source',{exact:true})).toBeVisible();
 await expect(page.locator('.sources-panel blockquote')).toContainText('ORCHID-742');
 await page.getByRole('textbox',{name:'Document question'}).fill('Who leads the project?');
 await expect(page.getByRole('button',{name:'Ask',exact:true})).toBeEnabled();
 const answer=await page.locator('.answer').innerText();
 const sid=await page.evaluate(()=>localStorage.getItem('docuchat-session'));
 const checked=await page.getByRole('checkbox',{name:'orchid.pdf'}).isChecked();
 const mutations=[]; page.on('request',r=>{if(r.url().includes('/api/')&&r.method()!=='GET')mutations.push(r.url());});
 await mkdir('docs/images',{recursive:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'docs/images/docuchat-en.png',fullPage:true});
 await page.getByRole('button',{name:'简体中文',exact:true}).click();
 await expect(page.locator('html')).toHaveAttribute('lang','zh-CN');
 await expect(page.getByRole('heading',{name:'文档',exact:true})).toBeVisible();
 await expect(page.getByRole('textbox',{name:'文档问题'})).toHaveValue('Who leads the project?');
 await expect(page.locator('.answer')).toContainText('ORCHID-742');
 expect(await page.evaluate(()=>localStorage.getItem('docuchat-session'))).toBe(sid);
 expect(await page.getByRole('checkbox',{name:'orchid.pdf'}).isChecked()).toBe(checked);
 await expect(page.getByRole('link',{name:'打开 PDF 第 1 页'}).first()).toHaveAttribute('href',/#page=1$/);
 await page.screenshot({path:'docs/images/docuchat-zh-CN.png',fullPage:true});
 await page.getByRole('button',{name:'English',exact:true}).click();
 expect(await page.locator('.answer').innerText()).toBe(answer);
 expect(mutations).toEqual([]);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'docs/images/docuchat-mobile.png',fullPage:true});
 await page.locator('input[type=file]').setInputFiles(path.resolve('fixtures/invalid.txt'));
 await expect(page.getByRole('alert').last()).toContainText('Choose a PDF');
 await page.getByRole('button',{name:'简体中文',exact:true}).click();
 await expect(page.getByRole('alert').last()).toContainText('PDF');
 await expect(page.getByRole('alert').last()).not.toContainText('Choose a PDF');
 await page.reload();
 await expect(page.locator('html')).toHaveAttribute('lang','zh-CN');
 await expect(page.locator('.answer')).toContainText('ORCHID-742');
 await expect(page.getByRole('checkbox',{name:'orchid.pdf'})).toBeChecked();
 await page.getByRole('button',{name:'English',exact:true}).click();
 await page.route('**/api/chat',r=>r.fulfill({status:502,contentType:'application/json',body:JSON.stringify({error:{code:'MODEL_FAILED',message:'PRIVATE_UNTRANSLATED_MESSAGE'}})}));
 await page.getByRole('textbox',{name:'Document question'}).fill('failure');
 await page.getByRole('button',{name:'Ask',exact:true}).click();
 await expect(page.getByRole('alert').last()).toContainText('model');
 await expect(page.locator('body')).not.toContainText('PRIVATE_UNTRANSLATED_MESSAGE');
 await page.getByRole('button',{name:'简体中文',exact:true}).click();
 await expect(page.getByRole('alert').last()).toContainText('模型服务调用失败');
});
test('switching language during a pending stream does not cancel or restart it',async({page})=>{
 await page.goto('/');
 await page.locator('input[type=file]').setInputFiles(path.resolve('fixtures/orchid.pdf'));
 await expect(page.locator('.document-item')).toContainText('Available');
 await page.getByRole('button',{name:'New session',exact:true}).click();
 let release; const gate=new Promise(r=>release=r);let calls=0;
 await page.route('**/api/chat',async route=>{calls++; await gate; await route.fulfill({status:200,contentType:'text/event-stream',body:'event: done\ndata: '+JSON.stringify({answer:'Original English answer',supported:false,citations:[],retrieved:[]})+'\n\n'});});
 await page.getByRole('textbox',{name:'Document question'}).fill('Keep answering');
 await page.getByRole('button',{name:'Ask',exact:true}).click();
 await expect.poll(()=>calls).toBe(1);
 await page.getByRole('button',{name:'简体中文',exact:true}).click();
 await expect(page.getByRole('button',{name:'停止生成'})).toBeVisible();
 release();
 await expect(page.locator('.answer')).toContainText('Original English answer');
 expect(calls).toBe(1);
});
